#!/usr/bin/env python3
"""Compile tokens/design-tokens.json into consumable artifacts.

Emits (no tree files are rewritten — the parity gate enforces tree == SOT):
  tokens/design-tokens.compiled.css  — CSS custom properties for every tree
  tokens/design-tokens.compiled.json — flat effective map per tree (for
                                        proxied organs: AAA :3001, WELL :18083,
                                        arifOS :8088 — they read JSON, not CSS)

Usage:
  python3 scripts/compile-design-tokens.py           # write artifacts
  python3 scripts/compile-design-tokens.py --check   # fail if artifacts are stale
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOKENS_DIR = HERE.parent / "tokens"
SOT = TOKENS_DIR / "design-tokens.json"
CSS_OUT = TOKENS_DIR / "design-tokens.compiled.css"
JSON_OUT = TOKENS_DIR / "design-tokens.compiled.json"


def build(sot):
    tokens, trees = sot["tokens"], sot["trees"]
    css = ["/* GENERATED by scripts/compile-design-tokens.py — do not edit by hand.",
           f"   source: tokens/design-tokens.json v{sot['version']} ({sot['updated']}) */",
           ":root {"]
    for name, spec in tokens.items():
        note = spec.get("role", "")
        if spec.get("textUse") == "forbidden":
            note += " — decorative only, never as text"
        css.append(f"  --{name}: {spec['value']};{' ' * max(1, 46 - len(name))}/* {note} */")
    css.append("}")
    flat = {}
    for tree_name, tree in trees.items():
        overrides = tree.get("overrides", {})
        flat[tree_name] = {
            "file": tree["file"],
            "label": tree["label"],
            "values": {n: overrides.get(n, s["value"]).upper() for n, s in tokens.items()},
        }
    return "\n".join(css) + "\n", flat


def main() -> int:
    sot = json.loads(SOT.read_text())
    css, flat = build(sot)
    check = "--check" in sys.argv
    if check:
        problems = []
        if not CSS_OUT.exists() or CSS_OUT.read_text() != css:
            problems.append(f"{CSS_OUT.name} is stale — re-run the compiler")
        if not JSON_OUT.exists() or json.loads(JSON_OUT.read_text()) != flat:
            problems.append(f"{JSON_OUT.name} is stale — re-run the compiler")
        if problems:
            print("compile-design-tokens --check FAILED:")
            for p in problems:
                print("  -", p)
            return 1
        print(f"compile-design-tokens --check PASS (v{sot['version']}, {len(flat)} trees)")
        return 0
    CSS_OUT.write_text(css)
    JSON_OUT.write_text(json.dumps(flat, indent=2) + "\n")
    print(f"compiled {len(sot['tokens'])} tokens × {len(sot['trees'])} trees → "
          f"{CSS_OUT.name}, {JSON_OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
