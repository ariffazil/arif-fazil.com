#!/usr/bin/env node
/**
 * generate-makcik-meta.cjs — zen D2 (F13 ratified 2026-11-23).
 *
 * Closes the last arrow of the ratified MAKCIKGPT_TRUTH_LINEAGE pipeline:
 *
 *   essays.json (single metadata SOT: identity, series, claims, seal, dest)
 *     ⋈ meta.presentation.json (authored per-article: subtitle, domain,
 *        excerpt, temporal_validity)
 *     → meta.generated.ts (makcikArticlesMeta for the SPA)
 *
 * Article BODIES stay in per-slug .ts files (ArticleContent). Membership and
 * every canonical field come from essays.json through makcik-source.cjs, so
 * the SPA archive, feed.xml, sitemap.xml and llms.* can no longer disagree.
 * Drift is a BUILD FAILURE: the slug sets must match exactly.
 *
 * Retires the opposite-direction drift engine generate-essays-json.cjs
 * (TS-as-canon, zero callers, contradicted the ratified lineage doc).
 */
const fs = require("fs");
const path = require("path");
const { getMakcikSource, computeCanonicalPayloadHash } = require("./lib/makcik-source.cjs");

const SITE_ROOT = path.resolve(__dirname, "..");
const PRESENTATION = path.join(SITE_ROOT, "src/data/makcikgpt/meta.presentation.json");
const OUT = path.join(SITE_ROOT, "src/data/makcikgpt/meta.generated.ts");

const { pieces } = getMakcikSource(); // throws MakcikSourceError on validation failure
const presentation = JSON.parse(fs.readFileSync(PRESENTATION, "utf8"));

const essaySlugs = new Set(pieces.map((p) => p.dest.path.replace(/\/$/, "").split("/").pop()));

// essays.json uses JSON null for "absent"; the TS contract uses optional fields.
// Project null → omission inside nested claim/source/evidence objects.
function stripNulls(v) {
  if (Array.isArray(v)) return v.map(stripNulls);
  if (v && typeof v === "object") {
    const out = {};
    for (const [k, val] of Object.entries(v)) {
      if (val !== null) out[k] = stripNulls(val);
    }
    return out;
  }
  return v;
}
const presSlugs = new Set(Object.keys(presentation));
const missingPres = [...essaySlugs].filter((s) => !presSlugs.has(s));
const orphanPres = [...presSlugs].filter((s) => !essaySlugs.has(s));
if (missingPres.length || orphanPres.length) {
  console.error("✗ MAKCIK PARITY FAIL — essays.json ↔ meta.presentation.json slug sets differ");
  if (missingPres.length) console.error("  in essays.json, missing presentation:", missingPres);
  if (orphanPres.length) console.error("  in presentation, missing essays.json entry:", orphanPres);
  process.exit(1);
}

const meta = pieces.map((p) => {
  const slug = p.dest.path.replace(/\/$/, "").split("/").pop();
  const pres = presentation[slug];
  const m = {
    slug,
    title: p.title,
    subtitle: pres.subtitle,
    date: p.date,
    domain: pres.domain,
    language: p.lang === "bm" ? "ms" : p.lang,
    excerpt: pres.excerpt,
    tags: p.tags,
    seal: p.seal,
    provenance_status: p.provenance_status || "legacy",
    claim_register: stripNulls(p.claim_register || []),
    source_ledger: stripNulls(p.source_ledger || []),
    counter_evidence: stripNulls(p.counter_evidence || []),
    version_lineage: stripNulls(p.version_lineage || { version: "1.0", published: p.date, last_updated: p.date }),
    merkle_leaf: computeCanonicalPayloadHash(p),
  };
  if (pres.temporal_validity) m.temporal_validity = pres.temporal_validity;
  return m;
});

const header = `// GENERATED by scripts/generate-makcik-meta.cjs — DO NOT EDIT BY HAND.
// Metadata SOT: src/data/essays.json (via scripts/lib/makcik-source.cjs).
// Presentation SOT: src/data/makcikgpt/meta.presentation.json.
// Regenerated on every prebuild; parity drift fails the build.
import type { MakcikArticleMeta } from './types';

export const makcikArticlesMeta: MakcikArticleMeta[] = `;

fs.writeFileSync(OUT, header + JSON.stringify(meta, null, 2) + ";\n");
console.log(`✓ makcik meta generated: ${meta.length} articles (essays.json ⋈ presentation), parity OK`);
